import assert from 'node:assert/strict';
import { validate, vaeTiling, enginePayload } from './core.mjs';
import { chooseMode, engineFeatures, engineArgs } from './engine-manager.mjs';
const hw={cpuAvailable:true,gpus:[{id:'CUDA0',name:'NVIDIA GeForce GTX 1070',runtime:'runtime-v0.2.1',integrated:false}]};
const auto=chooseMode('auto',hw);
assert.equal(auto.mode,'hybrid');
assert.equal(auto.backend,'all=cpu,diffusion=CUDA0,vae=CUDA0');
const fast=engineFeatures(auto,'pascal-fast');
assert.equal(fast.attention,'flash');
assert.equal(fast.convDirect,false);assert.equal(fast.vaeTiled,false);
const direct=engineFeatures(auto,'pascal-direct');assert.equal(direct.convDirect,true);
const tiled=engineFeatures(auto,'pascal-tiled');assert.equal(tiled.vaeTiled,true);
assert.equal(vaeTiling(512,512,fast).enabled,false);
assert.equal(vaeTiling(512,512,tiled).enabled,true);
const args=engineArgs(auto,0,7872,fast);
assert.ok(args.includes('--diffusion-fa'));assert.ok(!args.includes('--sage-attn'));assert.ok(!args.includes('--vae-conv-direct'));assert.ok(args.includes('--offload-to-cpu'));
assert.equal(validate({prompt:'x'}).profile,'pascal-fast');
assert.throws(()=>validate({prompt:'x',profile:'sage'}));
assert.equal(enginePayload(validate({prompt:'x',width:512,height:512}),0,fast).vae_tiling_params.enabled,false);
console.log('PASS Qwen Imagen Pascal: hybrid auto + Flash + Pascal VAE + no Sage.');
